print(f"  Базовый уровень конверсии (A): {baseline_conversion*100:.1f}%")
print(f"  Ожидаемый уровень конверсии (B): {expected_conversion*100:.1f}%")
print(f"  Относительный lift: {(expected_conversion/baseline_conversion - 1)*100:.1f}%")
print(f"  Абсолютное изменение: {(expected_conversion - baseline_conversion)*100:.1f} п.п.")
print(f"  Мощность теста: {power*100:.0f}%")
print(f"  Уровень значимости (α): {alpha*100:.0f}%")
