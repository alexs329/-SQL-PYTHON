print(f"Размер выборки (СПб): {len(spb):,}")
print(f"\nСредняя активность (Москва): {moscow.mean():.2f} часов")
print(f"Средняя активность (СПб): {spb.mean():.2f} часов")
print(f"Разница (СПб - Москва): {spb.mean() - moscow.mean():.2f} часов")
print(f"\nt-статистика = {t_stat:.4f}")
print(f"p-value = {p_value:.6f}")
print("="*50)

