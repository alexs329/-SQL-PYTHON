# 
# ### 3. Вывод (интерпретация)
# 
# **p-value = {p_value:.6f}**
# 
# Так как p-value **{ 'меньше' if p_value < 0.05 else 'больше' }** уровня значимости 0.05, мы **{ 'отвергаем' if p_value < 0.05 else 'не отвергаем' }** нулевую гипотезу.
