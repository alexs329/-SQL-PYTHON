# ### 1. Методология
# 
# Для проверки гипотезы был использован **односторонний независимый t-тест** (one‑tailed independent t‑test).
# 
# **Почему выбран этот тест:**
# - Сравниваются две независимые группы (пользователи Москвы и Санкт‑Петербурга).
