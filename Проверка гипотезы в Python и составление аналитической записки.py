# Данные уже загружены в переменную df (из задания 5.1)
# Фильтруем Москву и Санкт-Петербург
df_filtered = df[df['city'].isin(['Москва', 'Санкт-Петербург'])].copy()

# Проверяем и удаляем дубликаты по puid (как требовал ревьюер)
# Находим puid, которые встречаются в нескольких городах
puid_city_count = df_filtered.groupby('puid')['city'].nunique()
puid_in_multiple_cities = puid_city_count[puid_city_count > 1]

# Создаём чистый DataFrame без пересекающихся пользователей
if len(puid_in_multiple_cities) > 0:
    df_clean = df_filtered[~df_filtered['puid'].isin(puid_in_multiple_cities.index)].copy()
    print(f"Удалено пересекающихся пользователей: {len(puid_in_multiple_cities)}")
else:
    df_clean = df_filtered.copy()
    print("Пересекающихся пользователей не найдено")

# Берём столбец с активностью 'hours' из очищенных данных
moscow = df_clean[df_clean['city'] == 'Москва']['hours']
spb = df_clean[df_clean['city'] == 'Санкт-Петербург']['hours']

# Проверка дисперсий
_, p_levene = stats.levene(moscow, spb)
equal_var = p_levene >= 0.05

# Односторонний t-тест (СПб > Москва)
t_stat, p_value = stats.ttest_ind(spb, moscow, alternative='greater', equal_var=equal_var)

# Вывод результатов
print("="*50)
print("ЗАДАНИЕ 6.2: Проверка гипотезы (с очищенными данными)")
